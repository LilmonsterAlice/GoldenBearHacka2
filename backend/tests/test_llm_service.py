def test_unsupported_featherless_number_uses_grounded_fallback(client, monkeypatch):
    monkeypatch.setenv("FEATHERLESS_API_KEY", "test-key-not-real")

    async def ungrounded(self, **kwargs):
        return {
            "answer": "This saves $999.",
            "risk": "No risk.",
            "recommendation": "Apply immediately.",
            "gpu_related": True,
        }

    monkeypatch.setattr(FeatherlessClient, "generate_json", ungrounded)
    response = client.post(
        "/api/chat",
        json={
            "question": "Why is this recoverable?",
            "opportunity_id": "idle-interactive",
        },
    )

    body = response.json()
    assert "$999" not in body["answer"]
    assert "not guaranteed savings" in body["answer"]
    assert any("ungrounded response" in caveat for caveat in body["caveats"])


