def test_featherless_wording_preserves_authoritative_citations(
    client, monkeypatch
):
    monkeypatch.setenv("FEATHERLESS_API_KEY", "test-key-not-real")

    async def generated(self, *, system_prompt, user_prompt):
        assert "Never invent" in system_prompt
        assert "synthetic-idle-123" in user_prompt
        return {
            "answer": "Investigate the stored 4–10 GPU-hours range; it is not guaranteed savings.",
            "risk": "Useful interactive work could be interrupted.",
            "recommendation": "Pilot a warning and idle timeout with an opt-out.",
            "gpu_related": True,
        }

    monkeypatch.setattr(FeatherlessClient, "generate_json", generated)
    response = client.post(
        "/api/chat",
        json={
            "question": "Why is this recoverable?",
            "opportunity_id": "idle-interactive",
        },
    )

    body = response.json()
    assert body["answer"].startswith("Investigate the stored 4–10 GPU-hours")
    assert body["finding_ids"] == ["synthetic-idle-123"]
    assert body["job_ids"] == [123]
    assert any("generated by Featherless" in caveat for caveat in body["caveats"])


